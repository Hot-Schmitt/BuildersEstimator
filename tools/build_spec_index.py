#!/usr/bin/env python3
"""Build spec/INDEX.md and spec/OPEN.md from the spec/ folder.

INDEX.md lists every id with what it is, its status and the one file that defines
it, so an agent reads one line and opens one file. OPEN.md lists everything still
open or proposed: it is the owner's queue for the next round of decisions.

Both pages are generated. Editing them by hand is pointless: the next run
overwrites them. They carry no date, so tools/check_spec.py can tell when they
are out of step with the folder.

Run:  python3 tools/build_spec_index.py
"""

import sys

import spec_lib

GENERATED = "**Generated by `tools/build_spec_index.py`. Do not edit by hand.**"
WAITING = {"open", "proposed", "options"}


def ordered(records):
    """Records grouped by kind, in the order of spec_lib.KIND_ORDER, then by id."""
    for kind in spec_lib.KIND_ORDER:
        rows = sorted((r for r in records if r["kind"] == kind), key=lambda r: r["id"])
        if rows:
            yield kind, rows


def cell(text):
    return str(text).replace("|", "/")


def index_page(spec):
    out = ["# Specification index", "", GENERATED, "",
           f"{len(spec.records)} id(s) defined. Find one with "
           "`grep -n \"<id>\" spec/INDEX.md`, then open the file on that line.", ""]
    if not spec.records:
        out += ["Nothing is recorded yet.", ""]
    for kind, rows in ordered(spec.records):
        out += [f"## {spec_lib.KIND_NAMES[kind]}", "",
                "| Id | What | Status | Home |", "|---|---|---|---|"]
        out += [f"| {r['id']} | {cell(r['title'])} | {r['status']} | `{r['file']}` |"
                for r in rows]
        out += [""]
    return "\n".join(out)


def open_page(spec):
    waiting = [r for r in spec.records if r["status"] in WAITING]
    noted = [r for r in spec.records if r.get("open_note") and r["status"] not in WAITING]
    out = ["# Open and proposed", "", GENERATED, "",
           "Everything not yet decided. `open` has no answer; `proposed` (or, on a "
           "feature build note, `options`) has a recommendation waiting on the owner.", "",
           f"{len(waiting)} waiting.", ""]
    if not waiting and not noted:
        out += ["Nothing is waiting.", ""]
    for status in ("open", "proposed", "options"):
        rows = sorted((r for r in waiting if r["status"] == status), key=lambda r: r["id"])
        if not rows:
            continue
        out += [f"## {status.capitalize()}", "", "| Id | What | Home |", "|---|---|---|"]
        for r in rows:
            what = r["title"] + (f" — {r['open_note']}" if r.get("open_note") else "")
            out.append(f"| {r['id']} | {cell(what)} | `{r['file']}` |")
        out += [""]
    if noted:
        out += ["## Decided, but with an open note", "", "| Id | Note | Home |", "|---|---|---|"]
        out += [f"| {r['id']} | {cell(r['open_note'])} | `{r['file']}` |"
                for r in sorted(noted, key=lambda r: r["id"])]
        out += [""]
    return "\n".join(out)


def pages(spec):
    """The two generated pages, as {path under spec/: text}."""
    return {"INDEX.md": index_page(spec), "OPEN.md": open_page(spec)}


def main():
    spec = spec_lib.load()
    if spec.problems:
        print("Problems found. The index was NOT written:\n", file=sys.stderr)
        for problem in spec.problems:
            print(f"  - {problem}", file=sys.stderr)
        sys.exit(1)
    spec.root.mkdir(exist_ok=True)
    for name, text in pages(spec).items():
        (spec.root / name).write_text(text, encoding="utf-8")
    waiting = sum(1 for r in spec.records if r["status"] in WAITING)
    print(f"Wrote spec/INDEX.md ({len(spec.records)} ids) and spec/OPEN.md ({waiting} waiting).")


if __name__ == "__main__":
    main()
